function fixture({ version = "0.3.0", change = "packages/pi/src/extension.ts", message = "fix(pi): retain the host gate", tag = true } = {}) {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "cursor-prepare-test-"))); temporary.push(root);
  // No global/user Git configuration, hooks, credential stores or real identity.
  const gitEnv = { PATH: process.env.PATH, HOME: root, XDG_CONFIG_HOME: root, GIT_CONFIG_NOSYSTEM: "1", GIT_CONFIG_GLOBAL: "/dev/null", LANG: "C" };
  const rawGit = (args: string[]) => execFileSync("git", ["-c", "user.name=release fixture", "-c", "user.email=fixture@example.invalid", "-c", "commit.gpgSign=false", "-c", "tag.gpgSign=false", "-c", "core.hooksPath=/dev/null", ...args], { cwd: root, env: gitEnv, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  const put = (path: string, text: string) => { mkdirSync(dirname(join(root, path)), { recursive: true }); writeFileSync(join(root, path), text); };
  rawGit(["init", "--initial-branch=main"]);
  const originals = sourceFiles(version);
  for (const [path, text] of originals) put(path, text);
  put("packages/pi/src/extension.ts", "export const fixture = 0;\n");
  put("packages/native/native/manifest.json", '{"version":"' + version + '","artifacts":{"fixture":"do not relabel"}}\n');
  put("packages/native/native/fixture.node", "synthetic binary, never load\n");
  rawGit(["add", "."]); rawGit(["commit", "--no-verify", "-m", "chore: initialize synthetic release fixture"]);
  const baseline = rawGit(["rev-parse", "HEAD"]).trim();
  const tags = new Map<string, Tag>();
  if (tag) { rawGit(["tag", "v" + version]); tags.set("v" + version, { object: baseline, commit: baseline }); }
  put(change, "accepted fixture change\n"); rawGit(["add", "--", change]); rawGit(["commit", "--no-verify", "-m", message]);
  const source = rawGit(["rev-parse", "HEAD"]).trim();
  const state = { main: source, tags, runs: [] as Run[], dispatches: 0, pushes: 0 };
  const env: Record<string, string> = { GITHUB_ACTIONS: "true", GITHUB_REPOSITORY: repository, GITHUB_REF: "refs/heads/main", GITHUB_WORKFLOW_REF: repository + "/.github/workflows/auto-release.yml@refs/heads/main", GITHUB_EVENT_NAME: "push", GITHUB_SHA: source, GITHUB_RUN_ID: "123", GITHUB_RUN_ATTEMPT: "1", AUTOMATED_NPM_RELEASES: "true" };
  const git = vi.fn((args: string[], options: { env: typeof env }): string => {
    expect(options.env).toBe(env);
    const command = unconfigure(args);
    if (command[0] === "ls-remote") {
      expect(command[1]).toBe("https://github.com/" + repository + ".git");
      const refs: Record<string, string> = { "refs/heads/main": state.main };
      for (const [name, value] of state.tags) {
        refs["refs/tags/" + name] = value.object;
        if (value.object !== value.commit) refs["refs/tags/" + name + "^{}"] = value.commit;
      }
      return command.slice(2).filter(ref => refs[ref]).map(ref => refs[ref] + "\t" + ref + "\n").join("");
    }
    if (command[0] === "push") {
      expect(command.slice(1, 4)).toEqual(["--atomic", "--porcelain", "https://github.com/" + repository + ".git"]);
      expect(command.join(" ")).not.toMatch(/--force|--mirror|--delete|\+refs/);
      const commit = command[4].split(":")[0], ref = command[5].split(":")[0], name = ref.slice("refs/tags/".length);
      expect(rawGit(["rev-parse", commit + "^"]).trim()).toBe(state.main);
      expect(state.tags.has(name)).toBe(false);
      state.main = commit; state.tags.set(name, { object: rawGit(["rev-parse", ref]).trim(), commit }); state.pushes++;
      return "synthetic atomic push accepted\n";
    }
    if (command[0] === "fetch") {
      expect(command).toContain("--no-write-fetch-head");
      expect(command[3]).toBe("https://github.com/" + repository + ".git");
      // Objects are already in this isolated fixture. Never invoke real fetch.
      return "";
    }
    return rawGit(args);
  });
  const gh = vi.fn((args: string[], options: { env: typeof env }): string => {
    expect(options.env).toBe(env);
    if (args[0] === "api") {
      expect(args).toContain("repos/" + repository + "/actions/workflows/publish.yml/runs");
      expect(args).toContain("--hostname");
      return JSON.stringify({ total_count: state.runs.length, workflow_runs: state.runs });
    }
    expect(args.slice(0, 3)).toEqual(["workflow", "run", "publish.yml"]);
    const name = args[args.indexOf("--ref") + 1];
    expect(state.tags.has(name)).toBe(true);
    state.dispatches++;
    state.runs.push({ id: 300 + state.dispatches, event: "workflow_dispatch", head_sha: state.tags.get(name)!.commit, head_branch: name });
    return "";
  });
  const options = { projectRoot: root, env, force: false, preview: false };
  return { root, originals, source, baseline, state, env, options, git, gh, rawGit, put, run: () => prepareRelease(options, { git, gh }) };
}
function useLocalBareRemote(f: ReturnType<typeof fixture>, beforePush?: (remote: string) => void) {
  const remote = realpathSync(mkdtempSync(join(tmpdir(), "cursor-prepare-bare-"))); temporary.push(remote);
  f.rawGit(["init", "--bare", remote]);
  f.rawGit(["push", remote, f.source + ":refs/heads/main", "refs/tags/v0.3.0:refs/tags/v0.3.0"]);
  const implementation = f.git.getMockImplementation()!, hookDirectories: string[] = [];
  f.git.mockImplementation((args, options) => {
    const command = unconfigure(args);
    if (["ls-remote", "push", "fetch"].includes(command[0])) {
      if (command[0] === "push") {
        const hooks = args.filter(arg => arg.startsWith("core.hooksPath=")).at(-1)!.slice("core.hooksPath=".length);
        hookDirectories.push(hooks);
        expect(existsSync(join(hooks, "pre-push"))).toBe(true);
        beforePush?.(remote);
      }
      // Redirect the transport itself, not just the advertised ref result. Every
      // real push here goes exclusively to this fixture's local bare repository.
      const output = f.rawGit(args.map(arg => arg === "https://github.com/" + repository + ".git" ? remote : arg));
      if (command[0] === "push") {
        const commit = command[4].split(":")[0], ref = command[5].split(":")[0];
        f.state.main = commit; f.state.tags.set(ref.slice("refs/tags/".length), { object: f.rawGit(["rev-parse", ref]).trim(), commit }); f.state.pushes++;
      }
      return output;
    }
    return implementation(args, options);
  });
  return { remote, hookDirectories };
}
